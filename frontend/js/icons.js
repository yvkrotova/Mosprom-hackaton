// Подставляет иконки в разметку вида <i data-icon="bell"></i>.
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll("i[data-icon]")) {
    el.outerHTML = icon(el.dataset.icon, el.className);
  }
}
